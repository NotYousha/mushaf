/**
 * Write the landing page's word-sync demo from the app's own data.
 *
 * The page's whole argument is that the mushaf follows the voice word by word,
 * and the only honest way to make that argument is with the same layout and
 * timing data the app itself uses, against the same recording. A video would be
 * smaller and would be lying about what the app does.
 *
 * Which is why this is generated rather than typed. Five words of scripture
 * hand-maintained in an HTML file will eventually disagree with the timings
 * they are drawn against, and nobody will notice until the highlight is a word
 * behind on the front page of the site.
 *
 * Run with `npm run landing`.
 */

import { readFileSync, writeFileSync } from 'node:fs'

const SURAH = 97 // Al-Qadr — short, famous, and its audio is the one bundled.

/**
 * Ayah 3: "the Night of Decree is better than a thousand months".
 *
 * Chosen because its word count and its timing count agree exactly. They do not
 * for every ayah here — ayah 1 carries the basmala, which is four words the
 * timings do not cover, and ayah 2 is off by one for reasons that belong to the
 * alignment data rather than to this script. The check below is what makes that
 * a build failure rather than a silent drift on the front page.
 */
const AYAH = 3

const timings = JSON.parse(readFileSync('data/timings-burhaji-nabawi.json', 'utf8'))
const text = JSON.parse(readFileSync('data/quran-text.json', 'utf8'))

if (timings.unit !== 'ms') {
  throw new Error(`Expected timings in ms, got ${timings.unit}.`)
}

const ayat = timings.surahs[String(SURAH)]
if (!ayat) throw new Error(`No timings for surah ${SURAH}.`)

const entry = ayat.find(([n]) => n === AYAH)
if (!entry) throw new Error(`No timings for ${SURAH}:${AYAH}.`)
const [, starts] = entry

const verse = text[String(SURAH)]?.[AYAH - 1]
if (!verse) throw new Error(`No text for ${SURAH}:${AYAH}.`)

const words = verse.split(/\s+/).filter(Boolean)

if (words.length !== starts.length) {
  throw new Error(
    `${SURAH}:${AYAH} has ${words.length} words but ${starts.length} timings. ` +
      `They have to agree or the highlight runs ahead of the voice. ` +
      `Pick a different ayah, or find out why the alignment disagrees.`,
  )
}

/*
 * Where the last word ends.
 *
 * There is no start time after it, so the next ayah's first word is used, and
 * for a final ayah a second is added. Being slightly generous is right: the
 * highlight lingering a moment on the last word looks like a held note, while
 * cutting early looks like a bug.
 */
const next = ayat.find(([n]) => n === AYAH + 1)
const end = next ? next[1][0] : starts[starts.length - 1] + 1000

const ms = (v) => (v / 1000).toFixed(3)

const spans = words
  .map((w, i) => {
    const from = ms(starts[i])
    const to = ms(i + 1 < starts.length ? starts[i + 1] : end)
    return `          <span class="dw" data-t="${from}" data-t-end="${to}">${w}</span>`
  })
  .join('\n')

const block = [
  `          <!-- demo:start -->`,
  `          <!-- Generated by scripts/build-landing.mjs from data/timings-burhaji-nabawi.json`,
  `               and data/quran-text.json. Surah ${SURAH}, ayah ${AYAH}. Do not edit by hand. -->`,
  spans,
  `          <!-- demo:end -->`,
].join('\n')

/*
 * The landing page sits at the repo root rather than in landing/, because Vite
 * mirrors an input's source path into dist: from landing/index.html the site's
 * front door would have been served at /mushaf/landing/. Its stylesheet and its
 * module stay in landing/ -- only the document has to be at the root.
 */
const page = 'index.html'
const html = readFileSync(page, 'utf8')

const startMark = html.indexOf('<!-- demo:start -->')
const endMark = html.indexOf('<!-- demo:end -->')
if (startMark === -1 || endMark === -1) {
  throw new Error('index.html is missing its demo:start / demo:end markers.')
}

// Back up to the start of the marker's own line so indentation stays clean.
const lineStart = html.lastIndexOf('\n', startMark) + 1
const lineEnd = endMark + '<!-- demo:end -->'.length

// lineStart is the beginning of the marker's own line, so the block carries its
// own indentation and none is stripped.
const out = html.slice(0, lineStart) + block + html.slice(lineEnd)

// The audio is the whole surah, so the demo has to know where its ayah sits in
// it. Published on the figure rather than computed in the browser, because the
// browser has no access to the timings.
const withRange = out
  .replace(/data-demo-from="[^"]*"/, `data-demo-from="${ms(starts[0])}"`)
  .replace(/data-demo-to="[^"]*"/, `data-demo-to="${ms(end)}"`)

writeFileSync(page, withRange)

console.log(
  `landing: ${SURAH}:${AYAH}, ${words.length} words, ` +
    `${ms(starts[0])}s–${ms(end)}s of burhaji-${String(SURAH).padStart(3, '0')}.mp3`,
)
